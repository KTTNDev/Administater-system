import {beforeEach,afterEach,it,expect,vi} from 'vitest';
import fs from 'node:fs';import path from 'node:path';import os from 'node:os';
import {db} from '../src/lib/db';
import {writeOffice,listOffice,copyAnnualOffice} from '../src/lib/office-db';
import {readTaskAlertSettings,writeTaskAlertSettings} from '../src/lib/task-alert-db';
import {getTaskAlerts,updateTaskAlert} from '../src/app/task-alert-actions';
import {setStorage,exportWorkspace} from '../src/lib/storage';
import {prepareBackupRestore,activateBackupRestore} from '../src/lib/workspace-restore';
vi.mock('next/cache',()=>({revalidatePath:vi.fn()}));
vi.mock('../src/lib/auth',()=>({requireUser:vi.fn(async()=>{})}));
let folder:string;
beforeEach(()=>{folder=fs.mkdtempSync(path.join(os.tmpdir(),'sarabun-alert-'));vi.stubEnv('DATABASE_PATH',path.join(folder,'data.sqlite'));vi.stubEnv('SARABUN_SOURCE_DIR',folder);fs.mkdirSync(path.join(folder,'scripts'));fs.copyFileSync('scripts/restore-backup.mjs',path.join(folder,'scripts/restore-backup.mjs'));setStorage(path.join(folder,'files'),'','');});
afterEach(()=>{db().close();(globalThis as unknown as {sarabunDb?:unknown}).sarabunDb=undefined;vi.useRealTimers();vi.unstubAllEnvs();});
const read=(id:string)=>listOffice().find(item=>item.id===id)!;
it('snooze expires into an unread reminder and later thresholds require fresh acknowledgement',async()=>{
 vi.useFakeTimers();vi.setSystemTime(new Date('2026-11-05T05:00:00Z'));
 const id=writeOffice({kind:'task',title:'ตรวจช่วงการเตือน',due:'2026-11-08'});
 let alert=(await getTaskAlerts()).alerts.find(a=>a.task.id===id)!;expect(alert.phase).toBe('before:3');
 await updateTaskAlert({id:alert.id,taskId:id,phase:alert.phase,operation:'ack'});
 await updateTaskAlert({id:alert.id,taskId:id,phase:alert.phase,operation:'snooze',until:'2026-11-06'});
 vi.setSystemTime(new Date('2026-11-06T05:00:00Z'));alert=(await getTaskAlerts()).alerts.find(a=>a.task.id===id)!;
 expect(alert.snoozed).toBe(false);expect(alert.acknowledged).toBe(false);
 await updateTaskAlert({id:alert.id,taskId:id,phase:alert.phase,operation:'ack'});
 vi.setSystemTime(new Date('2026-11-07T05:00:00Z'));alert=(await getTaskAlerts()).alerts.find(a=>a.task.id===id)!;
 expect(alert.phase).toBe('before:1');expect(alert.acknowledged).toBe(false);
});
it('persists acknowledgement and snooze, rejects stale events, and alerts again after reopening',async()=>{
 const id=writeOffice({kind:'task',title:'งานติดตาม',due:'2020-01-01'});
 let alerts=await getTaskAlerts();expect(alerts.alerts).toHaveLength(1);
 let alert=alerts.alerts[0];expect(alert.acknowledged).toBe(false);
 let action=await updateTaskAlert({id:alert.id,taskId:id,phase:alert.phase,operation:'ack'});expect(action.ok).toBe(true);
 expect((await getTaskAlerts()).alerts[0].acknowledged).toBe(true);
 action=await updateTaskAlert({id:alert.id,taskId:id,phase:alert.phase,operation:'snooze',until:'2099-01-01'});expect(action.ok).toBe(true);
 expect((await getTaskAlerts()).alerts[0].snoozed).toBe(true);
 expect((await getTaskAlerts()).alerts[0].acknowledged).toBe(false);
 writeOffice({...read(id),due:'2021-01-01'},id,read(id).version);
 expect((await updateTaskAlert({id:alert.id,taskId:id,phase:alert.phase,operation:'ack'})).ok).toBe(false);
 expect((await getTaskAlerts()).alerts[0].acknowledged).toBe(false);
 writeOffice({...read(id),status:'done'},id,read(id).version);expect((await getTaskAlerts()).alerts).toHaveLength(0);
 writeOffice({...read(id),status:'working'},id,read(id).version);
 expect(read(id).taskReminder.cycle).toBe(1);expect((await getTaskAlerts()).alerts[0].acknowledged).toBe(false);
 const project=writeOffice({kind:'project',title:'โครงการพัก',fiscalYear:2570});
 const child=writeOffice({kind:'task',title:'งานย่อย',projectId:project,due:'2020-01-01'});
 writeOffice({...read(project),archived:true},project,read(project).version);
 expect((await getTaskAlerts()).alerts.some(a=>a.task.id===child)).toBe(false);
});
it('calculates authoritative due dates, preserves them for progress changes, and resets annual reminder dates',()=>{
 const settings=readTaskAlertSettings();writeTaskAlertSettings({...settings.settings,holidays:['2026-11-09']},0);
 const id=writeOffice({kind:'task',title:'งานนับวัน',date:'2026-11-06',due:'2026-12-31',annual:true,fiscalYear:2570,taskDeadline:{mode:'duration',days:3,count:'business',start:'next'},taskReminder:{dates:['2026-11-10']}});
 expect(read(id).due).toBe('2026-11-12');
 const updated=readTaskAlertSettings();writeTaskAlertSettings({...updated.settings,holidays:[]},updated.version);
 writeOffice({...read(id),taskPercent:25},id,read(id).version);expect(read(id).due).toBe('2026-11-12');
 const next=copyAnnualOffice(id,read(id).version);expect(read(next).taskReminder.dates).toEqual(['2027-11-10']);expect(read(next).taskReminder.cycle).toBe(0);
 expect(()=>writeTaskAlertSettings(settings.settings,0)).toThrow();
});
it('includes notification preferences and acknowledgements in backup and restore',async()=>{
 const id=writeOffice({kind:'task',title:'สำรองแจ้งเตือน',due:'2020-01-01'});
 const current=(await getTaskAlerts()).alerts[0];await updateTaskAlert({id:current.id,taskId:id,phase:current.phase,operation:'ack'});
 const first=readTaskAlertSettings();writeTaskAlertSettings({...first.settings,offsets:[7,2,0]},first.version);
 const newAlert=(await getTaskAlerts()).alerts[0];await updateTaskAlert({id:newAlert.id,taskId:id,phase:newAlert.phase,operation:'ack'});
 const backup=exportWorkspace();expect(backup.counts.task_alerts).toBeGreaterThanOrEqual(2);
 const latest=readTaskAlertSettings();writeTaskAlertSettings({...latest.settings,enabled:false},latest.version);
 const preview=await prepareBackupRestore(path.basename(backup.folder));activateBackupRestore(preview.token,'กู้คืนข้อมูล');
 expect(readTaskAlertSettings().settings.enabled).toBe(true);
 expect((await getTaskAlerts()).alerts[0].acknowledged).toBe(true);
});
