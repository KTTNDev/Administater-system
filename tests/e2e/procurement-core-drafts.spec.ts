import {test,expect} from '@playwright/test';
import {sampleCase} from '../../src/lib/procurement/workspace/samples';
import type {LinkedCoreDraft} from '../../src/lib/procurement/core/bindings';
import fs from 'node:fs';
import JSZip from 'jszip';
import {PDFDocument} from 'pdf-lib';

test.skip(!process.env.SARABUN_E2E_DATA_ROOT,'Only create Core procurement samples in an isolated database');
test('creates fifteen linked Core drafts, opens the standard editor and explicitly Syncs shared amounts',async({page})=>{
  test.setTimeout(300000);
  await page.goto('/?view=procurement');
  const record=sampleCase(1520),title=`ทดสอบเชื่อม Core ${Date.now()}`;
  record.caseInput.projectTitleShort=title;
  record.agency.codes.internalMemoPrefix='ทดสอบ Core '+record.caseInput.id;
  record.agency.codes.externalLetterPrefix=record.agency.codes.internalMemoPrefix;
  record.agency.codes.poPrefix=record.agency.codes.internalMemoPrefix;
  record.caseInput.docs.doc6_2_inspectorOrder.runningNo=String(Date.now());
  const headers={Origin:new URL(page.url()).origin};
  const savedResponse=await page.request.post('/api/procurement/workspace',{headers,data:{action:'save',payload:record}});expect(savedResponse.ok()).toBe(true);
  const saved=await savedResponse.json();
  await page.reload();await page.getByRole('button',{name:new RegExp(title)}).click();
  const bridge=page.getByRole('region',{name:'ร่างหนังสือในระบบหลัก',exact:true});
  await bridge.getByRole('button',{name:'สร้าง/อัปเดตชุดร่างเอกสาร',exact:true}).click();
  await expect(bridge.getByText('เชื่อมร่างครบ 15 ฉบับแล้ว เปิดแก้ไขได้ในระบบร่างหนังสือ',{exact:true})).toBeVisible({timeout:45000});
  await bridge.locator('summary').click();
  await expect(bridge.getByRole('button',{name:'เปิดร่าง',exact:true})).toHaveCount(15);
  const getLinks=async()=>{const response=await page.request.get(`/api/procurement/core-drafts?caseId=${record.caseInput.id}`);expect(response.ok()).toBe(true);return await response.json() as LinkedCoreDraft[];};
  const links=await getLinks();expect(links).toHaveLength(15);
  for(const [id,layout] of Object.entries({'4.1':'procurement-tor','10':'procurement-po','11.2':'procurement-inspection','11.3':'procurement-photos'}))expect(links.find(link=>link.doc_id===id)!.draft!.layout).toBe(layout);
  expect(links.find(link=>link.doc_id==='1')!.draft!.phone).toBe(record.agency.phoneDisplay);
  expect(links.find(link=>link.doc_id==='11.1')!.draft!.phone).toBe('');
  await page.getByRole('navigation',{name:'ขั้นตอนกรอกข้อมูล'}).getByRole('button',{name:/2 รายการ/}).click();
  await page.getByLabel('ราคาต่อหน่วย 1',{exact:true}).fill('700');
  page.once('dialog',dialog=>dialog.accept());
  await bridge.getByRole('button',{name:'สร้าง/อัปเดตชุดร่างเอกสาร',exact:true}).click();
  await expect(bridge.getByRole('status').filter({hasText:'อัปเดตเนื้อหาแล้ว'})).toBeVisible({timeout:45000});
  const afterUiSync=await getLinks();expect(afterUiSync.map(link=>link.draft_id)).toEqual(links.map(link=>link.draft_id));
  expect(afterUiSync.find(link=>link.doc_id==='10')!.draft!.body).toContain('๑,๗๔๐.๐๐');
  await page.getByRole('navigation',{name:'ลายแทงเรียงแฟ้ม'}).getByRole('button',{name:'เอกสาร 10 ใบสั่งซื้อ',exact:true}).click();
  const frame=page.frameLocator('iframe[title="ตัวอย่างหนังสือ A4"]');
  await expect(frame.locator('#pages .document-table')).toContainText('๑,๗๔๐.๐๐',{timeout:30000});
  await expect(frame.locator('#pages .signature')).toHaveCount(0);
  await expect(page.getByLabel('ชื่อ–นามสกุลผู้ลงนาม')).toHaveCount(0);
  await expect(page.locator('.signature-editor')).toHaveCount(1);
  await expect(page.locator('.floating-editor')).toHaveCount(1);
  await expect(page.getByLabel('เพิ่ม PDF หรือรูปภาพ (เลือกหลายไฟล์ได้)',{exact:true})).toHaveCount(1);
  await expect(frame.locator('#pages .procurement-metadata>div')).toHaveCount(2);
  await expect(frame.locator('#pages .procurement-signatures .signature')).toHaveCount(0);
  await expect(frame.locator('#pages .procurement-words')).toHaveCSS('text-align','center');
  fs.mkdirSync('output/core-mapper',{recursive:true});await page.screenshot({path:'output/core-mapper/core-editor-po.png'});
  const currentResponse=await page.request.get('/api/procurement/workspace?action=list');expect(currentResponse.ok()).toBe(true);
  const changed=(await currentResponse.json()).find((row:{caseInput:{id:string}})=>row.caseInput.id===record.caseInput.id);changed.caseInput.items[0].unitPrice=700;changed.caseInput.projectTitleShort='งานหลัง Sync';
  const savedAgain=await page.request.post('/api/procurement/workspace',{headers,data:{action:'save',payload:changed}});expect(savedAgain.ok()).toBe(true);const latest=await savedAgain.json();
  const sync=await page.request.post('/api/procurement/core-drafts',{timeout:60000,headers,data:{caseId:record.caseInput.id,caseVersion:latest.version,mode:'sync',expectedVersions:Object.fromEntries(afterUiSync.map(link=>[link.doc_id,link.draft!.version]))}});expect(sync.ok()).toBe(true);
  const synced=await sync.json() as LinkedCoreDraft[];
  expect(synced.find(link=>link.doc_id==='10')!.draft!.body).toContain('๑,๗๔๐.๐๐');
  expect(synced.find(link=>link.doc_id==='11.3')!.draft!.appendixTitle).toContain('งานหลัง Sync');
  expect(synced.map(link=>link.draft_id)).toEqual(links.map(link=>link.draft_id));
  const po=synced.find(link=>link.doc_id==='10')!;
  const pdf=await page.request.get(`/api/documents/${po.draft_id}/pdf`,{timeout:120000});expect(pdf.status(),pdf.headers()['content-type']==='application/json'?await pdf.text():'Core PDF').toBe(200);
  const pdfBytes=await pdf.body();expect((await PDFDocument.load(pdfBytes)).getPageCount()).toBeGreaterThan(0);fs.writeFileSync('output/core-mapper/core-po.pdf',pdfBytes);
  const word=await page.request.get(`/api/documents/${po.draft_id}/word`,{timeout:120000});expect(word.status(),word.headers()['content-type']==='application/json'?await word.text():'Core Word').toBe(200);
  const wordBytes=await word.body(),xml=await (await JSZip.loadAsync(wordBytes)).file('word/document.xml')!.async('string');expect(xml).toContain('๑,๗๔๐.๐๐');expect(xml).toContain(record.caseInput.vendor.shopName);fs.writeFileSync('output/core-mapper/core-po.docx',wordBytes);
  const forbidden=await page.request.post('/api/procurement/core-drafts',{headers:{Origin:'https://foreign.invalid'},data:{caseId:record.caseInput.id,caseVersion:latest.version,mode:'create'}});expect(forbidden.status()).toBe(403);
});
