import {test,expect} from '@playwright/test';
import JSZip from 'jszip';
import fs from 'node:fs';
test('selected text spacing and Shift+Enter survive preview and source toggle',async({page})=>{
 await page.goto('/?view=templates');await page.locator('.template-feature').first().click();
 await page.getByRole('button',{name:'ใช้ข้อมูลตัวอย่าง',exact:true}).click();
 await page.getByLabel('เลขที่หนังสือ',{exact:true}).fill('');
 const subject='ตรวจจัดข้อความ '+Date.now();await page.getByLabel('เรื่อง / ชื่อร่าง').fill(subject);
 await page.locator('#document-body').fill('บรรทัดแรก');
 const editor=page.locator('.body-editor').filter({has:page.locator('#document-body')});
 await editor.getByRole('button',{name:'โหมดจัดข้อความแบบ Word',exact:true}).click();
 const input=page.locator('#document-body');await input.click();await input.press('Control+End');await input.press('Shift+Enter');await input.pressSequentially('บรรทัดสอง');
 await input.press('Enter');await input.pressSequentially('ย่อหน้าใหม่');
 await input.evaluate(el=>{const text=el.querySelector('p')?.firstChild||el.firstChild!;const r=document.createRange();r.setStart(text,0);r.setEnd(text,3);const s=getSelection()!;s.removeAllRanges();s.addRange(r);el.dispatchEvent(new MouseEvent('mouseup',{bubbles:true}));});
 await editor.getByLabel('ระยะตัวอักษรที่เลือก').selectOption('-0.3');await editor.getByRole('button',{name:'ใช้กับข้อความที่เลือก',exact:true}).click();
 const paper=page.frameLocator('iframe[title="ตัวอย่างหนังสือ A4"]');
 await expect(paper.locator('[data-tracking="-0.3"]')).toBeVisible();
 await page.screenshot({path:'output/typography-editor.png'});await expect(paper.locator('br[data-soft-break]')).toHaveCount(1);
 await expect(paper.locator('.body-text').filter({hasText:'ย่อหน้าใหม่'})).toBeVisible();
 await editor.getByRole('button',{name:'กลับโหมดข้อความ / ตาราง',exact:true}).click();
 await expect(page.locator('#document-body')).toHaveValue(/\[space=-0.3\].*\u2028บรรทัดสอง\nย่อหน้าใหม่/);
 const download=page.waitForEvent('download');
 const response=page.waitForResponse(r=>r.url().endsWith('/word'));
 await page.getByRole('button',{name:'ดาวน์โหลด Word',exact:true}).click();
 const result=await response;expect(result.status()).toBe(200);
 const file=await download;const zip=await JSZip.loadAsync(fs.readFileSync((await file.path())!));const xml=await zip.file('word/document.xml')!.async('string');
 expect(xml).toContain('w:spacing w:val="-6"');expect(xml).toMatch(/<w:br\s*\/>/);
 const pdf=await page.request.get(result.url().replace(/word$/,'pdf'));expect(pdf.status()).toBe(200);const bytes=await pdf.body();expect(bytes.subarray(0,5).toString()).toBe('%PDF-');fs.writeFileSync('output/typography-sample.pdf',bytes);
 await page.goto('/?view=dashboard');await page.getByLabel('ค้นหาเอกสารทุกข้อมูล').fill(subject);
 await page.getByRole('button',{name:new RegExp('^'+subject+' ')}).first().click();
 await expect(page.locator('#document-body')).toHaveValue(/\u2028บรรทัดสอง\nย่อหน้าใหม่/);
});
test('heading can be applied and returned to body text',async({page})=>{
 await page.goto('/?view=templates');await page.locator('.template-feature').first().click();await page.locator('#document-body').fill('หัวข้อทดสอบ');
 const editor=page.locator('.body-editor').filter({has:page.locator('#document-body')});await editor.getByRole('button',{name:'โหมดจัดข้อความแบบ Word',exact:true}).click();
 await page.locator('#document-body').click();await editor.getByRole('button',{name:'หัวข้อ',exact:true}).click();
 const paper=page.frameLocator('iframe[title="ตัวอย่างหนังสือ A4"]');await expect(paper.locator('.body-subheading')).toHaveText('หัวข้อทดสอบ');
 await editor.getByRole('button',{name:'เนื้อหา',exact:true}).click();await expect(paper.locator('.body-subheading')).toHaveCount(0);
});
